import './common.css';

interface DataTableProps {
  caption: string;
  columns: string[];
  rows: React.ReactNode[][];
}

/** Scrollable technical table; the caption is visually hidden but read by screen readers. */
export function DataTable({ caption, columns, rows }: DataTableProps) {
  return (
    <div className="table-wrap">
      <table className="table">
        <caption className="visually-hidden">{caption}</caption>
        <thead>
          <tr>
            {columns.map((c) => (
              <th key={c} scope="col">
                {c}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((cells, i) => (
            <tr key={i}>
              {cells.map((cell, j) => (
                <td key={j}>{cell}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
